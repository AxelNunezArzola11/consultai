/**
 * Candidate Vetting Page — /project/[id]/vetting
 *
 * Shows candidates with vetting status:
 * - Consent gate (must accept before vetting)
 * - VettingCard for each candidate with trust score + matrix
 * - Side-by-side compare (select 2)
 * - Search bar (Postgres full-text)
 * - Human-review notice prominently displayed
 * - "How this is scored" global panel
 * - Shortlist button per candidate
 */

export const dynamic = "force-dynamic";

import { db } from "@/lib/db";
import { candidates, signals as signalsTable, projects } from "@/lib/db/schema";
import { eq, sql, inArray } from "drizzle-orm";
import { CandidatesVettingClient } from "./CandidatesVettingClient";

interface Props {
  params: Promise<{ id: string }>;
  searchParams: Promise<{ q?: string }>;
}

export default async function CandidatesVettingPage({ params, searchParams }: Props) {
  const { id: projectId } = await params;
  const resolvedSearch = await searchParams;
  const query = resolvedSearch.q?.trim() ?? "";

  // Load project for requirements
  const [project] = await db
    .select()
    .from(projects)
    .where(eq(projects.id, projectId));

  if (!project) {
    return <div className="p-6 text-muted-foreground">Project not found.</div>;
  }

  // Search candidates using Postgres full-text search
  // search_vector is added via migration (not in Drizzle schema) — use raw SQL for FTS query
  let candidateRows;
  if (query) {
    candidateRows = await db
      .select()
      .from(candidates)
      .where(
        sql`${candidates.projectId} = ${projectId}
          AND search_vector @@ plainto_tsquery('english', ${query})`
      )
      .orderBy(candidates.rank);
  } else {
    candidateRows = await db
      .select()
      .from(candidates)
      .where(eq(candidates.projectId, projectId))
      .orderBy(candidates.rank);
  }

  // Load signals for all candidates
  const candidateIds = candidateRows.map((c) => c.id);

  const signalRows =
    candidateIds.length > 0
      ? await db
          .select()
          .from(signalsTable)
          .where(inArray(signalsTable.candidateId, candidateIds))
      : [];

  // Group signals by candidate
  const signalsByCandidate: Record<string, typeof signalRows> = {};
  for (const sig of signalRows) {
    if (!signalsByCandidate[sig.candidateId]) {
      signalsByCandidate[sig.candidateId] = [];
    }
    signalsByCandidate[sig.candidateId].push(sig);
  }

  const requirements = ((project.acceptanceCriteria as Array<{ id: string; description: string }> | null) ?? []);

  const humanReviewNotice =
    "This vetting report is generated by an AI agent from public sources. " +
    "It is intended to assist your decision-making, not replace it. " +
    "The company always makes the final hiring decision.";

  const scoringFormula =
    "Trust score = Σ(signal_weight × confidence) / Σ(signal_weight), clamped to [0,1], rounded to 2dp. " +
    "Weights: github_repo=0.35, github_pr=0.30, portfolio=0.20, public_review=0.10, provided_link=0.05.";

  return (
    <CandidatesVettingClient
      projectId={projectId}
      candidates={candidateRows.map((c) => ({
        id: c.id,
        name: c.name,
        email: c.email,
        githubHandle: c.githubHandle,
        portfolioUrl: c.portfolioUrl,
        status: c.status,
        rank: c.rank,
        trustScore: c.trustScore ? parseFloat(c.trustScore) : null,
        vettingConsentAt: c.vettingConsentAt?.toISOString() ?? null,
        vettingRanAt: c.vettingRanAt?.toISOString() ?? null,
        canDo: c.canDo as Array<{ skill: string; state: string; evidenceSummary: string | null }> | null,
        cannotDo: c.cannotDo as Array<{ skill: string }> | null,
      }))}
      signalsByCandidate={Object.fromEntries(
        Object.entries(signalsByCandidate).map(([id, sigs]) => [
          id,
          sigs.map((s) => ({
            id: s.id,
            candidateId: s.candidateId,
            requirementId: s.requirementId,
            signalType: s.signalType as "github_repo" | "github_pr" | "portfolio" | "public_review" | "provided_link",
            sourceUrl: s.sourceUrl,
            retrievedAt: s.retrievedAt.toISOString(),
            contentHash: s.contentHash,
            extractedFact: s.extractedFact,
            quotedExcerpt: s.quotedExcerpt,
            confidence: parseFloat(s.confidence),
          })),
        ])
      )}
      requirements={requirements}
      humanReviewNotice={humanReviewNotice}
      scoringFormula={scoringFormula}
      initialQuery={query}
    />
  );
}
