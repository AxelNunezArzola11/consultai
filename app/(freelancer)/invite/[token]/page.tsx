"use client";

/**
 * NDA Acceptance page — /invite/[token]
 *
 * Phase 4: candidate visits this URL from the demo-inbox invite link.
 * They see:
 *   1. The sanitized project summary (NOT the full brief)
 *   2. The NDA document text
 *   3. A typed-name field, checkbox, and Accept button
 *
 * On acceptance:
 *   - POSTs to /api/nda/accept with token, typedName, agreed, documentHash
 *   - Shows booking-unlocked confirmation
 *
 * Security note: full brief is served ONLY after NDA acceptance,
 * and only if the DATABASE confirms NDA_SIGNED status.
 *
 * DEMO DISCLAIMER: Explicitly marked as a non-legally-validated e-signature demonstration.
 */

import { useState, useEffect } from "react";
import { useParams, useRouter } from "next/navigation";
import { sha256Hex } from "@/lib/nda/invite-token";

// ---------------------------------------------------------------------------
// Static NDA document text template (matches server-side generate.ts)
// In production this would be fetched from the API.
// ---------------------------------------------------------------------------

function buildNdaText(params: {
  projectTitle: string;
  companyName: string;
  candidateName: string;
  date: string;
}): string {
  const { projectTitle, companyName, candidateName, date } = params;
  return `NON-DISCLOSURE AGREEMENT (DEMONSTRATION ONLY)

⚠️  THIS IS A DEMONSTRATION E-SIGNATURE — NOT LEGALLY VALIDATED ⚠️
This document is generated by ConsultAI for hackathon demonstration purposes only.
It does not constitute a legally binding contract. Use Documenso or a qualified
legal service for production NDA enforcement.

Date: ${date}

Parties:
  Disclosing Party: ${companyName}
  Receiving Party:  ${candidateName}

Project: ${projectTitle}

1. Confidential Information
   The Receiving Party acknowledges that all information related to the above
   Project, including but not limited to technical specifications, business
   requirements, acceptance criteria, milestone plans, and financial terms,
   constitutes confidential information ("Confidential Information") of the
   Disclosing Party.

2. Obligations
   The Receiving Party agrees to: (a) keep all Confidential Information strictly
   confidential; (b) not disclose Confidential Information to any third party
   without prior written consent; (c) use Confidential Information solely for the
   purpose of evaluating and performing the Project.

3. Term
   This agreement is effective from the date of acceptance and remains in effect
   for two (2) years, or until the Project is publicly disclosed by the Disclosing
   Party, whichever comes first.

4. No Obligation
   Nothing in this agreement obligates either party to enter into any further
   agreement or business relationship.

5. Governing Law
   [DEMONSTRATION PLACEHOLDER — specify governing jurisdiction before production use]

TEMPLATE VERSION: 1.0.0
`;
}

// ---------------------------------------------------------------------------
// Component
// ---------------------------------------------------------------------------

export default function InvitePage() {
  const params = useParams();
  const router = useRouter();
  const token = typeof params.token === "string" ? params.token : "";

  const [step, setStep] = useState<"loading" | "form" | "accepted" | "error">("loading");
  const [errorMsg, setErrorMsg] = useState("");
  const [projectTitle, setProjectTitle] = useState("Demo Project");
  const [companyName] = useState("Demo Company");
  const [typedName, setTypedName] = useState("");
  const [agreed, setAgreed] = useState(false);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [bookingUrl, setBookingUrl] = useState<string | null>(null);

  // In a real implementation, we'd fetch the NDA details from a public endpoint.
  // For demo, we show the form directly after a short simulated load.
  useEffect(() => {
    if (!token) {
      setErrorMsg("Invalid or missing invite token.");
      setStep("error");
      return;
    }
    // Simulate loading project details
    const timer = setTimeout(() => {
      setStep("form");
    }, 500);
    return () => clearTimeout(timer);
  }, [token]);

  const today = new Date().toISOString().split("T")[0];
  const ndaText = buildNdaText({
    projectTitle,
    companyName,
    candidateName: typedName || "Candidate",
    date: today,
  });

  async function handleAccept(e: React.FormEvent) {
    e.preventDefault();
    if (!agreed || !typedName.trim()) return;

    setIsSubmitting(true);

    // Compute document hash from the exact text shown
    const finalNdaText = buildNdaText({
      projectTitle,
      companyName,
      candidateName: typedName.trim(),
      date: today,
    });
    const documentHash = sha256Hex(finalNdaText);

    try {
      const resp = await fetch("/api/nda/accept", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          token,
          typedName: typedName.trim(),
          agreed: true,
          documentHash,
        }),
      });

      if (resp.status === 200) {
        const data = await resp.json();
        setBookingUrl(data.bookingUrl ?? null);
        setStep("accepted");
      } else if (resp.status === 409) {
        setStep("accepted"); // already accepted
      } else {
        setErrorMsg("This invitation link is invalid, expired, or already used.");
        setStep("error");
      }
    } catch {
      setErrorMsg("A network error occurred. Please try again.");
      setStep("error");
    } finally {
      setIsSubmitting(false);
    }
  }

  if (step === "loading") {
    return (
      <div className="flex items-center justify-center min-h-[60vh] text-muted-foreground">
        Loading invitation…
      </div>
    );
  }

  if (step === "error") {
    return (
      <div className="max-w-lg mx-auto px-6 py-12 text-center space-y-4">
        <div className="text-4xl">⚠️</div>
        <h1 className="text-xl font-bold">Invitation Unavailable</h1>
        <p className="text-muted-foreground text-sm">{errorMsg}</p>
      </div>
    );
  }

  if (step === "accepted") {
    return (
      <div className="max-w-lg mx-auto px-6 py-12 text-center space-y-6">
        <div className="text-5xl">✅</div>
        <h1 className="text-2xl font-bold">NDA Accepted</h1>
        <p className="text-muted-foreground">
          Thank you, <strong>{typedName}</strong>. Your NDA has been accepted.
          Your booking link is now unlocked.
        </p>
        <div className="rounded-lg border bg-muted px-4 py-3 text-sm text-left space-y-1">
          <p className="font-medium">Next step:</p>
          <p className="text-muted-foreground">
            Book a consultation meeting using the link below (or go to your
            booking page).
          </p>
          {bookingUrl && (
            <a
              href={bookingUrl}
              className="text-blue-600 underline break-all text-xs"
              target="_blank"
              rel="noopener noreferrer"
            >
              {bookingUrl}
            </a>
          )}
        </div>
        <p className="text-xs text-muted-foreground">
          ⚠️ Demo only — this NDA acceptance is not legally binding.
        </p>
      </div>
    );
  }

  // form step
  return (
    <div className="max-w-2xl mx-auto px-6 py-10 space-y-6">
      {/* Demo disclaimer banner */}
      <div className="rounded-lg border border-amber-300 bg-amber-50 dark:bg-amber-950 px-4 py-3 text-sm text-amber-800 dark:text-amber-200">
        <strong>⚠️ Demo only:</strong> This is a demonstration e-signature — not legally
        validated. For production use, integrate Documenso or a qualified e-signature
        provider.
      </div>

      <div>
        <h1 className="text-2xl font-bold">NDA Invitation</h1>
        <p className="text-muted-foreground text-sm mt-1">
          You have been invited to review and sign a Non-Disclosure Agreement for{" "}
          <strong>{projectTitle}</strong>.
        </p>
      </div>

      {/* Sanitized project summary — shown before NDA acceptance */}
      <div className="rounded-lg border bg-muted px-4 py-4 space-y-2">
        <h2 className="text-sm font-semibold">Project Overview</h2>
        <p className="text-sm text-muted-foreground">
          You are viewing a sanitized summary. The full project brief, acceptance
          criteria, and attachments will be accessible only after you sign this NDA.
        </p>
        <div className="text-sm border rounded bg-background px-3 py-2">
          <p className="font-medium">{projectTitle}</p>
          <p className="text-muted-foreground text-xs mt-1">
            [Sanitized summary — full brief unlocked after NDA acceptance]
          </p>
        </div>
      </div>

      {/* NDA text */}
      <div className="rounded-lg border">
        <div className="px-4 py-3 border-b flex items-center justify-between">
          <h2 className="text-sm font-semibold">Non-Disclosure Agreement</h2>
          <span className="text-xs text-muted-foreground">Template v1.0.0</span>
        </div>
        <div className="px-4 py-4 max-h-64 overflow-y-auto">
          <pre className="text-xs text-muted-foreground whitespace-pre-wrap font-mono leading-relaxed">
            {buildNdaText({
              projectTitle,
              companyName,
              candidateName: typedName || "[Your name will appear here]",
              date: today,
            })}
          </pre>
        </div>
      </div>

      {/* Acceptance form */}
      <form onSubmit={handleAccept} className="space-y-4">
        <div className="space-y-1">
          <label className="text-sm font-medium" htmlFor="typedName">
            Type your full name to sign
          </label>
          <input
            id="typedName"
            type="text"
            placeholder="Your full name"
            value={typedName}
            onChange={(e) => setTypedName(e.target.value)}
            className="w-full border rounded-md px-3 py-2 text-sm bg-background focus:outline-none focus:ring-2 focus:ring-ring"
            required
            minLength={2}
            maxLength={120}
          />
        </div>

        <label className="flex items-start gap-3 cursor-pointer">
          <input
            type="checkbox"
            checked={agreed}
            onChange={(e) => setAgreed(e.target.checked)}
            className="mt-0.5 h-4 w-4 rounded border"
            required
          />
          <span className="text-sm">
            I have read and agree to the terms of this Non-Disclosure Agreement.
            I understand this is a <strong>demonstration e-signature</strong> and not
            a legally binding contract.
          </span>
        </label>

        <button
          type="submit"
          disabled={!agreed || !typedName.trim() || isSubmitting}
          className="w-full rounded-md bg-primary text-primary-foreground px-4 py-2 text-sm font-medium disabled:opacity-50 hover:bg-primary/90 transition-colors"
        >
          {isSubmitting ? "Accepting…" : "Accept NDA & Unlock Booking"}
        </button>

        <p className="text-xs text-muted-foreground text-center">
          Acceptance timestamp and document SHA-256 hash are recorded.
        </p>
      </form>
    </div>
  );
}
