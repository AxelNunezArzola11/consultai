/**
 * NDA generator — Phase 4
 *
 * Generates an NDA PDF using pdf-lib.
 * Returns both the PDF bytes and the exact document text (for SHA-256 hashing).
 *
 * IMPORTANT: This is a demonstration e-signature — not legally validated.
 * The UI and README must label this explicitly.
 *
 * Template: fills in project name, candidate name, company name, and date.
 * The SHA-256 hash of the EXACT document text is recorded at acceptance time
 * to bind the candidate to the specific version they signed.
 *
 * Source: consultai-plan.md §4 Phase 4 — Confidentiality Gate & NDA
 */

import { PDFDocument, StandardFonts, rgb, degrees } from "pdf-lib";
import { sha256Hex } from "./invite-token";

// ---------------------------------------------------------------------------
// Template version (bump on any wording change)
// ---------------------------------------------------------------------------

export const NDA_TEMPLATE_VERSION = "1.0.0";

// ---------------------------------------------------------------------------
// NDA text template
// ---------------------------------------------------------------------------

export function buildNdaText(params: {
  projectTitle: string;
  companyName: string;
  candidateName: string;
  date: string; // e.g. "2025-07-15"
}): string {
  const { projectTitle, companyName, candidateName, date } = params;

  return `NON-DISCLOSURE AGREEMENT (DEMONSTRATION ONLY)

⚠️  THIS IS A DEMONSTRATION E-SIGNATURE — NOT LEGALLY VALIDATED ⚠️
This document is generated by ConsultAI for hackathon demonstration purposes only.
It does not constitute a legally binding contract. Use Documenso or a qualified
legal service for production NDA enforcement.

Date: ${date}

Parties:
  Disclosing Party: ${companyName}
  Receiving Party:  ${candidateName}

Project: ${projectTitle}

1. Confidential Information
   The Receiving Party acknowledges that all information related to the above
   Project, including but not limited to technical specifications, business
   requirements, acceptance criteria, milestone plans, and financial terms,
   constitutes confidential information ("Confidential Information") of the
   Disclosing Party.

2. Obligations
   The Receiving Party agrees to: (a) keep all Confidential Information strictly
   confidential; (b) not disclose Confidential Information to any third party
   without prior written consent; (c) use Confidential Information solely for the
   purpose of evaluating and performing the Project.

3. Term
   This agreement is effective from the date of acceptance and remains in effect
   for two (2) years, or until the Project is publicly disclosed by the Disclosing
   Party, whichever comes first.

4. No Obligation
   Nothing in this agreement obligates either party to enter into any further
   agreement or business relationship.

5. Governing Law
   [DEMONSTRATION PLACEHOLDER — specify governing jurisdiction before production use]

TEMPLATE VERSION: ${NDA_TEMPLATE_VERSION}
`;
}

// ---------------------------------------------------------------------------
// PDF generator
// ---------------------------------------------------------------------------

export interface NdaGenerateResult {
  pdfBytes: Uint8Array;
  /** Exact text used for SHA-256 hashing — bind acceptance to this content */
  documentText: string;
  /** SHA-256 hex of documentText */
  documentHash: string;
}

export async function generateNdaPdf(params: {
  projectTitle: string;
  companyName: string;
  candidateName: string;
}): Promise<NdaGenerateResult> {
  const date = new Date().toISOString().split("T")[0];
  const documentText = buildNdaText({ ...params, date });
  const documentHash = sha256Hex(documentText);

  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const boldFont = await doc.embedFont(StandardFonts.HelveticaBold);

  const page = doc.addPage([595, 842]); // A4
  const { width, height } = page.getSize();

  // Watermark
  page.drawText("DEMONSTRATION ONLY", {
    x: 100,
    y: height / 2,
    size: 48,
    font,
    color: rgb(0.9, 0.9, 0.9),
    rotate: degrees(45),
    opacity: 0.3,
  });

  // Title
  page.drawText("NON-DISCLOSURE AGREEMENT", {
    x: 50,
    y: height - 60,
    size: 16,
    font: boldFont,
    color: rgb(0, 0, 0),
  });

  page.drawText("(DEMONSTRATION ONLY — NOT LEGALLY VALIDATED)", {
    x: 50,
    y: height - 85,
    size: 10,
    font,
    color: rgb(0.7, 0, 0),
  });

  // Body — wrap text manually
  const lines = documentText.split("\n");
  let y = height - 120;
  const lineHeight = 14;
  const margin = 50;
  const maxWidth = width - margin * 2;

  for (const rawLine of lines) {
    if (y < 60) {
      // Add a new page if we run out of space
      const newPage = doc.addPage([595, 842]);
      newPage.drawText("DEMONSTRATION ONLY", {
        x: 100,
        y: 421,
        size: 48,
        font,
        color: rgb(0.9, 0.9, 0.9),
        rotate: degrees(45),
        opacity: 0.3,
      });
      y = 842 - 60;
    }

    const line = rawLine.trim();
    if (!line) {
      y -= lineHeight;
      continue;
    }

    // Word-wrap long lines
    const words = line.split(" ");
    let currentLine = "";
    for (const word of words) {
      const test = currentLine ? `${currentLine} ${word}` : word;
      const testWidth = font.widthOfTextAtSize(test, 10);
      if (testWidth > maxWidth && currentLine) {
        const currentPage = doc.getPages()[doc.getPageCount() - 1];
        currentPage.drawText(currentLine, {
          x: margin,
          y,
          size: 10,
          font,
          color: rgb(0, 0, 0),
        });
        y -= lineHeight;
        currentLine = word;
      } else {
        currentLine = test;
      }
    }
    if (currentLine) {
      const currentPage = doc.getPages()[doc.getPageCount() - 1];
      currentPage.drawText(currentLine, {
        x: margin,
        y,
        size: 10,
        font,
        color: rgb(0, 0, 0),
      });
      y -= lineHeight;
    }
  }

  // Footer with hash
  const lastPage = doc.getPages()[doc.getPageCount() - 1];
  lastPage.drawLine({
    start: { x: 50, y: 50 },
    end: { x: width - 50, y: 50 },
    thickness: 0.5,
    color: rgb(0.5, 0.5, 0.5),
  });
  lastPage.drawText(`Document SHA-256: ${documentHash}`, {
    x: 50,
    y: 36,
    size: 7,
    font,
    color: rgb(0.5, 0.5, 0.5),
  });
  lastPage.drawText(`Template version: ${NDA_TEMPLATE_VERSION} | Generated: ${new Date().toISOString()}`, {
    x: 50,
    y: 26,
    size: 7,
    font,
    color: rgb(0.5, 0.5, 0.5),
  });

  const pdfBytes = await doc.save();
  return { pdfBytes, documentText, documentHash };
}
