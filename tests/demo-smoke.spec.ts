/**
 * Demo-mode browser smoke test (tests/demo-smoke.spec.ts).
 *
 * Drives the production build in DEMO_MODE through every main route with real
 * inputs: role select, project creation, AI planning chat, candidate vetting +
 * NDA signing, delivery verification, approvals (honest payout block),
 * dispute analysis, multi-agent dispatch, and demo reset. Captures
 * screenshots (desktop + tablet) and navigation timings in one pass.
 */

import { test, expect, type Page } from "@playwright/test";

const SHOTS = "/tmp/demo-shots";
const PROJECT = "demo-project-saas";
// Shared across serial tests (single worker): created project + invite link.
let createdProjectId = "";
let signedInviteHref = "";

const timings: Array<{ route: string; ms: number }> = [];

async function gotoTimed(page: Page, route: string) {
  const start = Date.now();
  const resp = await page.goto(route, { waitUntil: "domcontentloaded" });
  const ms = Date.now() - start;
  timings.push({ route, ms });
  expect(resp?.status(), `${route} responds`).toBeLessThan(500);
  return resp;
}

test.describe.serial("demo smoke", () => {
  test.beforeEach(async ({ page }) => {
    // Fresh context per test → establish the company role first (mirrors the
    // judge clicking through the landing page).
    await page.goto("/");
    await page.getByRole("button", { name: /Enter Company Dashboard/ }).click();
    await page.waitForURL("**/dashboard");
  });

  test("landing → company role → dashboard", async ({ page }) => {
    await gotoTimed(page, "/");
    await expect(page.getByText(/DEMO MODE/)).toBeVisible();
    await page.screenshot({ path: `${SHOTS}/01-landing.png` });
    await page.getByRole("button", { name: /Enter Company Dashboard/ }).click();
    await page.waitForURL("**/dashboard");
    await expect(page.getByText("Enterprise SaaS Implementation").first()).toBeVisible();
    await page.screenshot({ path: `${SHOTS}/02-dashboard.png`, fullPage: true });
  });

  test("create project + AI planning chat + approve & save", async ({ page }) => {
    await gotoTimed(page, "/project/new");
    await page.getByLabel("Project title").fill("Smoke Test Project");
    await page.getByLabel("Project brief").fill("A brief for the smoke test.");
    await page.getByRole("button", { name: "Continue to AI planning" }).click();
    await page.waitForURL(/\/project\/new\?projectId=.+/);
    // Reloading the planner must NOT create another draft (no write on GET).
    await page.reload();
    await page.getByPlaceholder("Describe your project…").fill("Plan this project");
    await page.getByRole("button", { name: "Send", exact: true }).click();
    await expect(page.getByText("SIMULATED PLANNING RUN").first()).toBeVisible({ timeout: 30000 });
    await page.screenshot({ path: `${SHOTS}/03-planner-chat.png` });
    const saveResp = page.waitForResponse(
      (r) => r.url().includes("/api/db/save-brief") && r.request().method() === "POST"
    );
    await page.getByRole("button", { name: /Approve & Save Plan/ }).first().click();
    expect((await saveResp).status()).toBe(200);
    createdProjectId = new URL(page.url()).searchParams.get("projectId") ?? "";
    expect(createdProjectId.length).toBeGreaterThan(0);
  });

  test("saved plan persists as workspace milestones (no dupes on re-POST)", async ({ page }) => {
    // Milestones generated by Approve & Save must appear in the workspace.
    await gotoTimed(page, `/project/${createdProjectId}/milestones`);
    await expect(page.getByText("Requirements & Architecture").first()).toBeVisible();
    await expect(page.getByText("Frontend Development").first()).toBeVisible();
    // Idempotent creation: repeating the same client-generated ID replays.
    const payload = { projectId: "audit-dupe-1", title: "Dupe Check" };
    const first = await page.request.post("/api/projects", { data: payload });
    expect(first.status()).toBe(201);
    expect(await first.json()).toMatchObject({ projectId: "audit-dupe-1", created: true });
    const second = await page.request.post("/api/projects", { data: payload });
    expect(second.status()).toBe(200);
    expect(await second.json()).toMatchObject({ projectId: "audit-dupe-1", created: false });
  });

  test("planning + operations + ai-ops dispatch", async ({ page }) => {
    await gotoTimed(page, `/planning?projectId=${PROJECT}`);
    await page.screenshot({ path: `${SHOTS}/04-planning.png` });
    await gotoTimed(page, "/operations");
    await expect(page.getByText("Enterprise SaaS Implementation").first()).toBeVisible({ timeout: 30000 });
    await page.screenshot({ path: `${SHOTS}/05-operations.png` });
    await gotoTimed(page, `/ai-ops?projectId=${PROJECT}`);
    await page.getByPlaceholder(/Describe an operational request/).fill(
      "Run a consolidated project review"
    );
    await page.getByRole("button", { name: /Dispatch Supervisor/ }).click();
    await expect(page.getByText(/SIMULATED supervisor run/).first()).toBeVisible({ timeout: 30000 });
    await page.screenshot({ path: `${SHOTS}/06-ai-ops.png`, fullPage: true });
  });

  test("vetting re-run + NDA generate → invite → sign", async ({ page }) => {
    await gotoTimed(page, `/project/${PROJECT}/vetting`);
    // Re-run vetting on the first candidate card; the simulated run must succeed.
    const vettingResp = page.waitForResponse(
      (r) => r.url().includes("/api/agent/vetting") && r.request().method() === "POST"
    );
    await page.getByRole("button", { name: "Re-run" }).first().click();
    expect((await vettingResp).status()).toBe(200);
    await expect(page.getByRole("button", { name: "Re-run" }).first()).toBeVisible({ timeout: 30000 });
    await page.screenshot({ path: `${SHOTS}/07-vetting.png` });

    await gotoTimed(page, `/project/${PROJECT}/candidates`);
    // Only the shortlisted candidate (Lena) offers Send NDA — unique button.
    await page.getByRole("button", { name: "Send NDA" }).click();
    const inviteLink = page.locator('a[href^="/invite/"]').first();
    await expect(inviteLink).toBeVisible({ timeout: 15000 });
    const href = await inviteLink.getAttribute("href");
    expect(href).toMatch(/^\/invite\/[^:]+:demo-/);

    await gotoTimed(page, href!);
    await expect(page.getByText("TechNova Solutions").first()).toBeVisible();
    await page.getByLabel("Type your full name to sign").fill("Lena Fischer");
    await page.getByRole("checkbox").check();
    await page.getByRole("button", { name: /Accept NDA/ }).click();
    await expect(page.getByText("NDA Accepted")).toBeVisible({ timeout: 15000 });
    await page.screenshot({ path: `${SHOTS}/08-invite-accepted.png` });
    signedInviteHref = href!;
  });

  test("consumed invite links cannot be reused", async ({ page }) => {
    await gotoTimed(page, signedInviteHref);
    await expect(page.getByText(/Already Accepted|Already Used/)).toBeVisible();
  });

  test("milestones funding honesty + approvals gate + dispute analysis", async ({ page }) => {
    await gotoTimed(page, `/project/${PROJECT}/milestones`);
    await expect(
      page.getByText(/PayPal funding is unavailable in offline demo mode/).first()
    ).toBeVisible();
    await page.screenshot({ path: `${SHOTS}/09-milestones.png` });

    await gotoTimed(page, `/project/${PROJECT}/approvals`);
    await expect(page.getByText(/4,324.20|4324.2/).first()).toBeVisible();
    const approveResp = page.waitForResponse(
      (r) => r.url().includes("/api/paypal/payout/approve") && r.request().method() === "POST"
    );
    await page.getByPlaceholder("freelancer@example.com").fill("maya.chen@example.com");
    await page.getByRole("button", { name: /Approve & Release Payout/ }).click();
    // The payout must be honestly refused — never a simulated success.
    expect((await approveResp).status()).toBe(503);

    await gotoTimed(page, `/project/${PROJECT}/disputes/demo-dispute-1`);
    await expect(page.getByText(/DEMO-DISP-001|waiting_for_seller/i).first()).toBeVisible();
    await page.getByRole("button", { name: /Analyze Dispute|Re-analyze/ }).click();
    await expect(page.getByText(/SIMULATED dispute analysis/)).toBeVisible({ timeout: 30000 });
    await page.screenshot({ path: `${SHOTS}/10-dispute.png`, fullPage: true });
  });

  test("reschedule authorize applies +3d propagation", async ({ page }) => {
    const ledgerBefore = await (
      await page.request.get(`/api/projects/${PROJECT}/ledger`)
    ).json();
    const beforeRow = (ledgerBefore.rows as Array<{ id: string; dueDate: string }>).find(
      (r) => r.id === "demo-ms-integration"
    );
    expect(beforeRow).toBeDefined();

    await gotoTimed(page, `/ai-ops?projectId=${PROJECT}`);
    const approveResp = page.waitForResponse(
      (r) => r.url().includes("/api/ai-ops/approve") && r.request().method() === "POST"
    );
    await page.getByRole("button", { name: /Authorize & Apply/ }).first().click();
    const approveBody = await (await approveResp).json();
    expect(approveBody.decision).toBe("approved");
    expect(approveBody.applied_schedule_adjustments).toBeGreaterThan(0);

    const ledgerAfter = await (
      await page.request.get(`/api/projects/${PROJECT}/ledger`)
    ).json();
    const afterRow = (ledgerAfter.rows as Array<{ id: string; dueDate: string }>).find(
      (r) => r.id === "demo-ms-integration"
    );
    const diffDays = Math.round(
      (new Date(afterRow!.dueDate).getTime() - new Date(beforeRow!.dueDate).getTime()) / 86400000
    );
    expect(diffDays).toBe(3);
  });

  test("proposal approval records decision without executing payout", async ({ page }) => {
    await gotoTimed(page, `/project/${PROJECT}/delivery`);
    const resp = await page.request.post("/api/delivery/propose/approve", {
      data: {
        proposalId: "demo-payprop-1",
        decision: "approved",
        recipientEmail: "maya.chen@example.com",
      },
    });
    expect(resp.status()).toBe(200);
    const body = await resp.json();
    expect(body.decision).toBe("approved");
    // The critical honesty assertion: no payout is ever executed in demo mode.
    expect(body.payoutExecuted).toBe(false);
    expect(body.payout).toBeNull();
    // Decision persists: a repeat approval is idempotent, not a second decision.
    const replay = await page.request.post("/api/delivery/propose/approve", {
      data: {
        proposalId: "demo-payprop-1",
        decision: "approved",
        recipientEmail: "maya.chen@example.com",
      },
    });
    expect(replay.status()).toBe(200);
    expect(await replay.json()).toMatchObject({ decision: "approved" });
  });

  test("pipeline polling is real and pausable", async ({ page }) => {
    await gotoTimed(page, `/project/${PROJECT}/candidates`);
    await expect(page.getByText(/Auto-refresh every 3s/)).toBeVisible();
    await page.getByRole("button", { name: "Pause" }).click();
    await expect(page.getByText(/Auto-refresh paused/)).toBeVisible();
    await page.getByRole("button", { name: "Resume" }).click();
    await expect(page.getByText(/Auto-refresh every 3s/)).toBeVisible();
  });

  test("freelancer role is blocked from company mutations (honest 403)", async ({ browser }) => {
    const ctx = await browser.newContext();
    const page = await ctx.newPage();
    await page.goto("/");
    await page.getByRole("button", { name: /Enter Consultant Workspace/ }).click();
    await page.waitForURL("**/freelancer");
    await page.goto("/project/new");
    await page.getByLabel("Project title").fill("Should Not Exist");
    await page.getByRole("button", { name: "Continue to AI planning" }).click();
    await expect(page.getByText(/company or admin role/)).toBeVisible({ timeout: 15000 });
    await ctx.close();
  });

  test("freelancer deliver + portals + admin reset", async ({ page }) => {
    await gotoTimed(page, "/freelancer");
    await expect(page.getByText("Freelancer Deliverables").first()).toBeVisible();
    await expect(page.getByText("Requirements & Architecture").first()).toBeVisible();
    await page.screenshot({ path: `${SHOTS}/11-freelancer.png` });

    await gotoTimed(page, "/deliver/demo-ms-frontend");
    await page.getByPlaceholder("https://github.com/owner/repo/pull/123").fill(
      "https://github.com/technova-demo/saas-platform/pull/95"
    );
    const verifyResp = page.waitForResponse(
      (r) => r.url().includes("/api/delivery/verify") && r.request().method() === "POST"
    );
    await page.getByRole("button", { name: "Submit PR" }).click();
    expect((await verifyResp).status()).toBe(200);
    await expect(page.getByText(/SIMULATED verification/).first()).toBeVisible({ timeout: 15000 });

    await gotoTimed(page, "/admin");
    await expect(page.getByText("Demo Control Center")).toBeVisible();
    await page.getByRole("button", { name: "Reset demo fixtures" }).click();
    await expect(page.getByText("Demo fixtures restored")).toBeVisible({ timeout: 15000 });
    await page.screenshot({ path: `${SHOTS}/12-admin.png`, fullPage: true });
  });

  test("tablet responsiveness pass", async ({ browser }) => {
    const ctx = await browser.newContext({
      viewport: { width: 834, height: 1112 },
      deviceScaleFactor: 2,
      isMobile: false,
      hasTouch: true,
    });
    const page = await ctx.newPage();
    await gotoTimed(page, "/dashboard");
    await page.screenshot({ path: `${SHOTS}/13-tablet-dashboard.png` });
    await gotoTimed(page, "/operations");
    await page.screenshot({ path: `${SHOTS}/14-tablet-operations.png` });
    await ctx.close();
  });

  test("ledger page renders demo project without error boundary", async ({ page }) => {
    await gotoTimed(page, `/project/${PROJECT}/ledger`);
    await expect(page.getByText("Enterprise SaaS Implementation").first()).toBeVisible();
    await expect(page.getByText("Milestone Payments")).toBeVisible();
    await expect(page.getByText(/could not load/)).not.toBeVisible();
    await page.screenshot({ path: `${SHOTS}/15-ledger.png`, fullPage: true });
  });

  test.afterAll(async () => {
    // eslint-disable-next-line no-console
    console.log(`\n[demo-smoke] navigation timings:\n${timings.map((t) => `  ${t.ms}ms ${t.route}`).join("\n")}`);
    for (const t of timings) {
      expect(t.ms, `${t.route} under 60s`).toBeLessThan(60000);
    }
  });
});
